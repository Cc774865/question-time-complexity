def run_benchmark() -> dict[str, Any]:
    papers = benchmark_papers()
    summary: dict[str, Any] = {}
    for name, items in papers.items():
        scored = [
            score_calibrated_problem(pid, stem, counts, role=role)
            for pid, star, role, stem, counts in items
        ]
        results = [r.pop("_result") for r in scored]
        set_tau = aggregate_set(results)
        rev_tau = aggregate_set(list(reversed(results)))

        # Star is kept in the benchmark items for the monotonicity cross-check;
        # it never enters score_calibrated_problem.
        by_star: dict[int, list[float]] = {}
        for item, r in zip(items, scored):
            star = item[1]
            by_star.setdefault(int(star), []).append(r["tau"])
        star_means = {s: sum(v) / len(v) for s, v in sorted(by_star.items())}
        stars = sorted(star_means)
        strictly_increasing = all(
            star_means[stars[i]] < star_means[stars[i + 1]]
            for i in range(len(stars) - 1)
        )
        summary[name] = {
            "question_count": len(scored),
            "set_tau": round(set_tau, 6),
            "order_invariant": abs(set_tau - rev_tau) < 1e-12,
            "star_mean_tau": {str(k): round(v, 6) for k, v in star_means.items()},
            "strictly_increasing_by_star": strictly_increasing,
            "problems": scored,
        }
    return summary


if __name__ == "__main__":
    data = run_benchmark()
    out_path = Path(__file__).resolve().parents[2] / "examples" / "benchmark_7papers_2to8star.json"
    out_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    for name, info in data.items():
        means = " < ".join(f"{s}★:{v:.3f}" for s, v in info["star_mean_tau"].items())
        print(f"{name:12s} | mono={info['strictly_increasing_by_star']} | set_tau={info['set_tau']:.4f} | {means}")
